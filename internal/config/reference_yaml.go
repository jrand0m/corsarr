package config

import (
	"bytes"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/jrand0m/corsarr/internal/plugin"
)

// defaultsHeader opens the commented default configuration file.
const defaultsHeader = `# corsarr configuration with every default, generated by ` + "`corsarr config defaults --format=yaml`" + `.
# Loading it as is gives the same settings as starting with no configuration at all.
# Lines starting with "#" are settings without a default and sections where you add your own
# entries (indexers, download clients, …); remove the "#" and fill them in to use them.
# Keys in angle brackets are placeholders: <name> is a name you choose, made of lower-case
# letters and digits. Secrets are best given as ${env:NAME} or ${file:/run/secrets/name}.
# Every setting is explained in docs/configuration.md and by ` + "`corsarr config defaults`" + `.
`

// commentWidth is where explanation comments wrap.
const commentWidth = 92

// DefaultsYAML renders a complete configuration file holding every default,
// each setting under its explanation.
func (s *Schema) DefaultsYAML() []byte {
	var b bytes.Buffer
	b.WriteString(defaultsHeader)
	for _, f := range s.Root.Fields {
		b.WriteString("\n")
		for _, l := range s.block(f.Name, f.Node, "").emit() {
			b.WriteString(strings.TrimRight(l, " ") + "\n")
		}
	}
	return b.Bytes()
}

// yamlBlock is one key with its explanation. An inactive block (nothing with
// a default below it) is written commented out.
type yamlBlock struct {
	doc    []string
	body   []string
	active bool
}

func (y yamlBlock) emit() []string {
	if y.active {
		return append(y.doc, y.body...)
	}
	out := append([]string{}, y.doc...)
	for _, l := range y.body {
		out = append(out, "# "+l)
	}
	return out
}

// plain is the block as it reads inside an already commented-out parent.
func (y yamlBlock) plain() []string { return append(append([]string{}, y.doc...), y.body...) }

func (s *Schema) block(name string, n *Node, inherit string) yamlBlock {
	switch n.Kind {
	case KindObject:
		return s.objectBlock(name, n)
	case KindMap:
		elem := s.block(NamePlaceholder, n.Elem, "")
		return yamlBlock{doc: comment(n.Doc), body: append([]string{name + ":"}, indent(elem.plain(), 2)...)}
	case KindList:
		return s.listBlock(name, n)
	case KindInstance:
		return yamlBlock{body: append([]string{name + ":"}, indent(s.instanceBody(n), 2)...)}
	}
	return leafBlock(name, n, inherit)
}

func (s *Schema) objectBlock(name string, n *Node) yamlBlock {
	kids := make([]yamlBlock, len(n.Fields))
	active := false
	for i, f := range n.Fields {
		kids[i] = s.block(f.Name, f.Node, "")
		active = active || kids[i].active
	}
	body := []string{name + ":"}
	for _, k := range kids {
		lines := k.plain()
		if active {
			lines = k.emit()
		}
		body = append(body, indent(lines, 2)...)
	}
	return yamlBlock{doc: comment(n.Doc), body: body, active: active}
}

func (s *Schema) listBlock(name string, n *Node) yamlBlock {
	body := []string{name + ":"}
	if n.Elem.Kind == KindObject {
		body = append(body, "  -")
		for _, f := range n.Elem.Fields {
			body = append(body, indent(s.block(f.Name, f.Node, "").plain(), 4)...)
		}
	} else {
		body = append(body, indent(comment(leafNote(n.Elem)), 2)...)
		body = append(body, "  -")
	}
	return yamlBlock{doc: comment(n.Doc), body: body}
}

// instanceBody is one example entry: the common fields, then each plugin's
// settings under a marker naming its type.
func (s *Schema) instanceBody(n *Node) []string {
	var out []string
	for _, f := range commonInstanceFields(n.Plugin, s.Plugins) {
		out = append(out, s.block(f.Name, f.Node, "").plain()...)
	}
	for _, m := range s.Plugins.List(n.Plugin) {
		out = append(out, "", "# ── with type: "+m.ID+" ("+m.Name+") ──")
		for _, f := range m.Settings {
			out = append(out, s.pluginBlock(f).plain()...)
		}
	}
	return out
}

func (s *Schema) pluginBlock(f plugin.Field) yamlBlock {
	n := fieldNode(f)
	if f.Default == nil || (n.Kind != KindMap && n.Kind != KindList) {
		return s.block(f.Key, n, f.Help)
	}
	var val bytes.Buffer
	enc := yaml.NewEncoder(&val)
	enc.SetIndent(2)
	_ = enc.Encode(f.Default) // plugin defaults are plain values
	lines := strings.Split(strings.TrimRight(val.String(), "\n"), "\n")
	return yamlBlock{doc: comment(f.Help), body: append([]string{f.Key + ":"}, indent(lines, 2)...)}
}

func leafBlock(name string, n *Node, inherit string) yamlBlock {
	doc := n.Doc
	if doc == "" {
		doc = inherit
	}
	b := yamlBlock{doc: comment(strings.TrimSpace(doc + " " + leafNote(n)))}
	if n.Default == "" || n.Kind == KindSecret {
		b.body = []string{name + ":"}
		return b
	}
	b.body, b.active = []string{name + ": " + yamlScalar(n)}, true
	return b
}

// yamlScalar writes a default so that YAML reads it back as the same text.
func yamlScalar(n *Node) string {
	v := canonicalDefault(n)
	switch n.Kind {
	case KindInt, KindNumber, KindBool:
		return v
	}
	out, _ := yaml.Marshal(v) // a string always marshals
	return strings.TrimRight(string(out), "\n")
}

// comment wraps text into "# " lines.
func comment(text string) []string {
	var out []string
	line := ""
	for _, w := range strings.Fields(text) {
		if line != "" && len(line)+1+len(w) > commentWidth {
			out = append(out, "# "+line)
			line = ""
		}
		line = strings.TrimSpace(line + " " + w)
	}
	if line != "" {
		out = append(out, "# "+line)
	}
	return out
}

func indent(lines []string, n int) []string {
	pad := strings.Repeat(" ", n)
	out := make([]string, len(lines))
	for i, l := range lines {
		if l != "" {
			l = pad + l
		}
		out[i] = l
	}
	return out
}
